"""New Earth analog candidates (spec 01, P1): top Earth twins for 3 lunar and 3 Mars targets, plus a Balkans table.

Usage: python scripts/new_candidates.py [--json data/new_candidates.json] [--md docs/new-candidates.md]

Every number comes from the live engine: engine.index (terrain_sim, 50 km non-maximum suppression),
engine.light.best_window (light_sim, 28-day window), score = 0.6 terrain_sim + 0.4 light_sim (spec mode
"terrain+light", the default for Moon/Mars -> Earth). The JSON is written first; the Markdown is rendered from it.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import time
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from engine import dem, index, light  # noqa: E402

W_TERRAIN, W_LIGHT = 0.6, 0.4
POOL = 150                 # terrain-ranked pool (after 50 km NMS) that is re-ranked with light
TOP = 5
TOP_BALKANS = 3
KNOWN_KM = 100.0
BALKANS = [13.0, 39.0, 30.0, 48.0]      # lon_min, lat_min, lon_max, lat_max (integrator's bbox)
TARGET_IDS = ["shackleton-rim", "malapert-massif", "jezero", "gale", "oxia-planum"]   # + site finder #1


def targets() -> list[dict]:
    allt = {t["id"]: t for t in yaml.safe_load((ROOT / "engine" / "targets.yaml").read_text())}
    out = [{k: allt[i][k] for k in ("id", "label", "body", "lat", "lon", "source_url")} for i in TARGET_IDS]
    from engine import site_finder as sf
    top = sf.rank()[0]
    out.insert(2, {"id": top["id"], "label": f"Site finder #1 ({top['id']})", "body": "moon", "lat": top["lat"],
                   "lon": top["lon"], "source_url": "docs/site-finder.md (engine.site_finder.rank, default weights)"})
    return out


def known_sites() -> list[dict]:
    return [k for k in yaml.safe_load((ROOT / "engine" / "known_analogs.yaml").read_text()) if k["body"] == "earth"]


def nearest_known(lat: float, lon: float, known: list[dict]) -> tuple[dict, float]:
    r = dem.RADIUS_M["earth"] / 1000.0
    d = index.haversine_km(lat, lon, np.array([k["lat"] for k in known]), np.array([k["lon"] for k in known]), r)
    i = int(np.argmin(d))
    return known[i], float(d[i])


def candidates(idx, t: dict, k: int, region=None, known=None) -> list[dict]:
    raw = idx.search(t["body"], t["lat"], t["lon"], to=["earth"], k=POOL, region=region)["results"]["earth"]
    rows = []
    for r in raw:
        w = light.best_window(t["body"], t["lat"], r["lat"])
        score = W_TERRAIN * r["terrain_sim"] + W_LIGHT * w["light_sim"]
        kn, dk = nearest_known(r["lat"], r["lon"], known)
        rows.append({"id": r["id"], "lat": round(r["lat"], 4), "lon": round(r["lon"], 4),
                     "country": r["place_label"] or None, "terrain_sim": round(r["terrain_sim"], 4),
                     "light_sim": round(w["light_sim"], 4), "window": f"{w['start']} to {w['end']}",
                     "score": round(score, 4), "status": "known" if dk <= KNOWN_KM else "new",
                     "nearest_known": kn["label"], "nearest_known_km": round(dk, 1)})
    rows.sort(key=lambda x: -x["score"])
    for i, r in enumerate(rows[:k], start=1):
        r["rank"] = i
    return rows[:k]


def build() -> dict:
    t0 = time.perf_counter()
    idx = index.load_index()
    known = known_sites()
    out = {"index": str(idx.path.name), "index_manifest_sha256_16": hashlib.sha256(
               (idx.path / "manifest.json").read_bytes()).hexdigest()[:16],
           "weights": {"terrain": W_TERRAIN, "light": W_LIGHT}, "mode": "terrain+light", "pool": POOL,
           "nms_km": index.NMS_KM, "known_radius_km": KNOWN_KM, "balkans_bbox": BALKANS,
           "known_analogs": [k["id"] for k in known], "targets": []}
    for t in targets():
        out["targets"].append({**t, "top": candidates(idx, t, TOP, known=known),
                               "balkans": candidates(idx, t, TOP_BALKANS, region=BALKANS, known=known)})
    out["built_utc"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    out["seconds"] = round(time.perf_counter() - t0, 1)
    return out


def _row(r: dict) -> str:
    known = f"known ({r['nearest_known']}, {r['nearest_known_km']:.0f} km)" if r["status"] == "known" else \
        f"new (nearest known: {r['nearest_known']}, {r['nearest_known_km']:.0f} km)"
    return (f"| {r['rank']} | {r['lat']:.3f}, {r['lon']:.3f} | {r['country'] or '—'} | {r['terrain_sim']:.3f} | "
            f"{r['light_sim']:.3f} | {r['score']:.3f} | {r['window']} | {known} |")


HEAD = "| # | lat, lon | country | terrain_sim | light_sim | score | best 28-day window | known / new |\n" \
       "|---|---|---|---|---|---|---|---|"


def render(d: dict) -> str:
    lines = [
        "# New Earth analog candidates",
        "",
        "Generated by `scripts/new_candidates.py` from `data/new_candidates.json` "
        f"(index `{d['index']}`, manifest {d['index_manifest_sha256_16']}, built {d['built_utc']}). Do not edit by hand.",
        "",
        "**What this is.** For each target, the Earth places whose **terrain shape** (slope, roughness, relief, "
        "curvature at a ~926 m grid) and **yearly sunlight regime** best match it. Score = "
        f"{d['weights']['terrain']} × terrain_sim + {d['weights']['light']} × light_sim (mode `{d['mode']}`). "
        "It says nothing about geology, chemistry, regolith, temperature or access. "
        "These are hypotheses for field scouting, not recommendations.",
        "",
        f"Method: the {d['pool']} best terrain matches after {d['nms_km']:.0f} km non-maximum suppression are re-ranked by "
        "score; light_sim and the window come from the 28-day best-window search of the analytic light model "
        "(docs/light.md). \"known\" = within "
        f"{d['known_radius_km']:.0f} km of a site in `engine/known_analogs.yaml`; \"new\" = not.",
        "",
        "Reading the numbers: terrain_sim and light_sim are each 0–1 (1 = identical). Lunar polar targets have a Sun "
        "that never rises more than ~1.5° above a flat horizon; no Earth site reproduces that, and light_sim only "
        "measures how close the 28-day elevation histogram gets (the best windows are local-winter months).",
        "",
        "Per-target ranges of terrain_sim among the listed candidates: " + "; ".join(
            f"{t['label'].split(' (')[0]} {min(r['terrain_sim'] for r in t['top']):.2f}–"
            f"{max(r['terrain_sim'] for r in t['top']):.2f}" for t in d["targets"]) +
        ". Low values mean even the best Earth terrain is a weak shape match for that target.",
        "",
    ]
    for t in d["targets"]:
        lines += [f"## {t['label']} — {t['body']}, {t['lat']}, {t['lon']}", "",
                  f"Coordinates: {t['source_url']}", "", HEAD] + [_row(r) for r in t["top"]] + [""]
    lines += [f"## Balkans (lon {d['balkans_bbox'][0]:g}–{d['balkans_bbox'][2]:g}, "
              f"lat {d['balkans_bbox'][1]:g}–{d['balkans_bbox'][3]:g})", "",
              "Best candidates inside the box for each target (same scoring; the box also covers parts of "
              "neighbouring countries).", ""]
    for t in d["targets"]:
        lines += [f"### {t['label']}", "", HEAD] + [_row(r) for r in t["balkans"]] + [""]
    n_new = sum(r["status"] == "new" for t in d["targets"] for r in t["top"])
    n_all = sum(len(t["top"]) for t in d["targets"])
    lines += [f"Summary: {n_new} of {n_all} global top-{TOP} candidates are \"new\" (> {d['known_radius_km']:.0f} km "
              f"from every listed known analog; {len(d['known_analogs'])} known sites). Possible reason (not tested): "
              "established analogs were chosen for geology, climate or logistics, which this engine does not model.",
              ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--json", type=Path, default=dem.ROOT / "data" / "new_candidates.json")
    ap.add_argument("--md", type=Path, default=ROOT / "docs" / "new-candidates.md")
    a = ap.parse_args(argv)
    d = build()
    a.json.parent.mkdir(parents=True, exist_ok=True)
    a.json.write_text(json.dumps(d, indent=1, ensure_ascii=False) + "\n")
    d = json.loads(a.json.read_text())
    a.md.write_text(render(d))
    print(json.dumps({"seconds": d["seconds"], "targets": len(d["targets"]),
                      "new": sum(r["status"] == "new" for t in d["targets"] for r in t["top"])}))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
